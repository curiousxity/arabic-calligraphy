/**
 * The colour the editing chrome draws in over a block's ink: the ink's hue
 * turned half-way round the wheel, pushed to a saturation and lightness
 * that read against both the ink and the paper. Grey or near-black ink has
 * no hue to flip, so the push is what keeps the outline visible there.
 */

const FALLBACK = "#f59e0b";

export function hexToHsl(hex: string): { h: number; s: number; l: number } | null {
  const m = /^#([0-9a-f]{3}|[0-9a-f]{6})$/i.exec(hex.trim());
  if (!m) return null;
  let v = m[1];
  if (v.length === 3) v = v.split("").map((c) => c + c).join("");
  const r = parseInt(v.slice(0, 2), 16) / 255;
  const g = parseInt(v.slice(2, 4), 16) / 255;
  const b = parseInt(v.slice(4, 6), 16) / 255;
  const max = Math.max(r, g, b), min = Math.min(r, g, b);
  const l = (max + min) / 2;
  const d = max - min;
  if (d === 0) return { h: 0, s: 0, l };
  const s = d / (1 - Math.abs(2 * l - 1));
  let h: number;
  if (max === r) h = ((g - b) / d) % 6;
  else if (max === g) h = (b - r) / d + 2;
  else h = (r - g) / d + 4;
  h *= 60;
  if (h < 0) h += 360;
  return { h, s, l };
}

export function hslToHex(h: number, s: number, l: number): string {
  const c = (1 - Math.abs(2 * l - 1)) * s;
  const x = c * (1 - Math.abs(((h / 60) % 2) - 1));
  const m = l - c / 2;
  let r = 0, g = 0, b = 0;
  if (h < 60) [r, g, b] = [c, x, 0];
  else if (h < 120) [r, g, b] = [x, c, 0];
  else if (h < 180) [r, g, b] = [0, c, x];
  else if (h < 240) [r, g, b] = [0, x, c];
  else if (h < 300) [r, g, b] = [x, 0, c];
  else [r, g, b] = [c, 0, x];
  const to = (v: number) => Math.round((v + m) * 255).toString(16).padStart(2, "0");
  return `#${to(r)}${to(g)}${to(b)}`;
}

export function complementOf(ink: string): string {
  const hsl = hexToHsl(ink);
  if (!hsl) return FALLBACK;
  // A colour with no hue (grey) is treated as the default navy's hue, so the
  // complement is the same warm tone the default ink gets.
  const h = hsl.s < 0.05 ? (215 + 180) % 360 : (hsl.h + 180) % 360;
  return hslToHex(h, Math.max(0.7, hsl.s), Math.min(0.6, Math.max(0.45, hsl.l)));
}
